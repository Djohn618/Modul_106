-- SQL Escape Room – Bankraub (MySQL)

CREATE DATABASE IF NOT EXISTS `bankraub` DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci;
USE `bankraub`;


DROP TABLE IF EXISTS escape_routes;
DROP TABLE IF EXISTS security_cameras;
DROP TABLE IF EXISTS transactions;
DROP TABLE IF EXISTS vault_access;
DROP TABLE IF EXISTS employees;
DROP TABLE IF EXISTS customers;

CREATE TABLE customers (
    customer_id INT PRIMARY KEY,
    first_name VARCHAR(50),
    last_name VARCHAR(50),
    city VARCHAR(50),
    risk_level VARCHAR(20)
);

CREATE TABLE employees (
    employee_id INT PRIMARY KEY,
    first_name VARCHAR(50),
    last_name VARCHAR(50),
    department VARCHAR(50),
    access_level INT
);

CREATE TABLE vault_access (
    access_id INT PRIMARY KEY,
    employee_id INT,
    access_time DATETIME,
    successful TINYINT(1)
);

CREATE TABLE transactions (
    transaction_id INT PRIMARY KEY,
    from_account INT,
    to_account INT,
    amount DECIMAL(12,2),
    transaction_time DATETIME,
    suspicious TINYINT(1)
);

CREATE TABLE security_cameras (
    camera_id INT PRIMARY KEY,
    location VARCHAR(100),
    status VARCHAR(20),
    last_active DATETIME
);

CREATE TABLE escape_routes (
    route_id INT PRIMARY KEY,
    route_name VARCHAR(100),
    blocked TINYINT(1),
    last_seen_vehicle VARCHAR(100)
);

